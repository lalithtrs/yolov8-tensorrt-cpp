#!/usr/bin/env python3
"""Insert results/results.md (plus the latency chart) into README.md between the RESULTS markers.

Run after scripts/make_results.py:   python3 tools/update_readme.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
START, END = '<!-- RESULTS:START -->', '<!-- RESULTS:END -->'


def main():
    readme = os.path.join(ROOT, 'README.md')
    res = open(os.path.join(ROOT, 'results', 'results.md')).read().strip().split('\n')
    if res and res[0].startswith('# '):
        res = res[1:]  # README already has its own "## Results" heading
    body = []
    for i, line in enumerate(res):
        if line.startswith('#'):
            line = '#' + line  # demote one level: "## X" -> "### X"
        body.append(line)
        # put the chart right after the intro paragraph, before the first table
        if i + 1 < len(res) and res[i + 1].startswith('| Variant'):
            body[-1:] = [line, '![Latency by stage](results/latency.png)', '']
    block = '\n'.join([START, '<!-- generated by tools/update_readme.py from results/results.md; do not edit -->',
                       *body, END])
    text = open(readme).read()
    if START not in text or END not in text:
        raise SystemExit(f'README.md needs the {START} / {END} markers')
    text = re.sub(re.escape(START) + r'.*?' + re.escape(END), lambda _: block, text, flags=re.S)
    open(readme, 'w').write(text)
    print('README.md results section updated')


if __name__ == '__main__':
    main()
